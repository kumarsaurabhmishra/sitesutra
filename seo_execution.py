"""Evidence-supported SEO improvements from the 31 October Search Console review."""
from pathlib import Path


def improve(g):
    pages = g['pages']
    route = '/services/seo-marketing/'
    title, body = pages[route]
    marker = '<h2>Who this is for</h2>'
    assert marker in body
    evidence = '''<h2>Review the audit format before you enquire</h2>
<p>A useful finding names the affected URL or template, records the evidence, explains why it matters, assigns an implementation owner and states how the change will be checked. Use the worksheet below to compare an audit proposal or organise an existing review.</p>
<p><a class="btn secondary" href="/downloads/technical-seo-audit-review.csv" download>Download the technical SEO audit worksheet ↗</a></p>
<p class="fine">Editable CSV planning tool. It does not scan a website, certify compliance, estimate rankings or replace a scoped audit.</p>'''
    pages[route] = (title, body.replace(marker, evidence + marker, 1))

    # The worksheet is generated by a blog article too. Keep a stable copy available
    # when this module is used independently of that article's generator.
    download = Path('dist/downloads/technical-seo-audit-review.csv')
    if not download.exists():
        download.parent.mkdir(parents=True, exist_ok=True)
        download.write_text(
            'review_area,scope_or_question,evidence_received,affected_urls_or_templates,'
            'priority_and_reason,implementation_owner,verification_step,review_status\n'
            'Audit boundary,"Domains, subdomains, platforms, environments and page types included",,,,,,Not reviewed\n'
            'Discovery,"Crawl source, sitemap comparison and internal-link paths",,,,,,Not reviewed\n'
            'Indexing controls,"Status codes, robots directives, canonicals and representative URL checks",,,,,,Not reviewed\n'
            'Site changes,"Redirect map, redirect-chain checks and broken-link evidence",,,,,,Not reviewed\n'
            'Page experience,"Field or lab source, test date, profile and representative templates",,,,,,Not reviewed\n'
            'Structured data,"Eligible page types, detected markup and validation evidence where relevant",,,,,,Not reviewed\n'
            'Priorities,"Impact, evidence, dependency and reason for ordering each finding",,,,,,Not reviewed\n'
            'Implementation,"Included fixes, exclusions, responsible owner and approval process",,,,,,Not reviewed\n'
            'Verification,"Live acceptance checks and items dependent on later crawl or field data",,,,,,Not reviewed\n'
            'Handover,"Finding register, relevant exports, access notes and review date",,,,,,Not reviewed\n'
        )
